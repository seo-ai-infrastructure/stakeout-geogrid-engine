import assert from "node:assert/strict";
import { randomBytes, createHash } from "node:crypto";
import { db } from "../packages/db/src/index.ts";
import { completePin, failPin } from "../apps/worker/src/finalize.ts";
import { grantCredits } from "../apps/web/lib/credits.ts";

async function main() {
  if (process.env.TEST_DATABASE !== "1") throw new Error("Use an isolated test database with TEST_DATABASE=1");
  const base = process.env.TEST_BASE_URL ?? "http://localhost:3000";
  const tag = `qa-${Date.now()}`;
  const email = `${tag}@example.invalid`;
  const sha = (v: string) => createHash("sha256").update(v).digest("hex");
  const token = randomBytes(32).toString("hex");
  await db.loginToken.create({ data: { hash: sha(token), email, expiresAt: new Date(Date.now() + 60000) } });
  const call = (path: string, init: RequestInit = {}) => fetch(base + path, { redirect: "manual", ...init });
  assert.equal((await call("/api/scans")).status, 401);
  assert.equal((await call("/api/artifacts?key=other.mp4")).status, 401);
  assert.equal((await call("/api/auth/verify", { method: "POST", headers: { Origin: "https://evil.example" }, body: new URLSearchParams({ token }) })).status, 403);
  const signIn = await call("/api/auth/verify", { method: "POST", headers: { Origin: base }, body: new URLSearchParams({ token }) });
  assert.equal(signIn.status, 303);
  const cookie = signIn.headers.get("set-cookie")!.split(";")[0];
  assert.match(signIn.headers.get("set-cookie")!, /HttpOnly/i);
  const replay = await call("/api/auth/verify", { method: "POST", headers: { Origin: base }, body: new URLSearchParams({ token }) });
  assert.match(replay.headers.get("location")!, /error=expired/);
  const expired = randomBytes(32).toString("hex");
  await db.loginToken.create({ data: { hash: sha(expired), email, expiresAt: new Date(0) } });
  const expiredResult = await call("/api/auth/verify", { method: "POST", headers: { Origin: base }, body: new URLSearchParams({ token: expired }) });
  assert.match(expiredResult.headers.get("location")!, /error=expired/);
  const user = await db.user.findUniqueOrThrow({ where: { email } });
  assert.equal(user.creditBalance, 0);
  const input = { keyword: "emergency plumber", targetBusiness: "QA Plumbing", targetType: "mobile_maps", centerLat: 28.0395, centerLng: -81.9498, zip: "33801", city: "Lakeland", stateCode: "FL", ispId: "123", gridSize: 3, spacingKm: 1 };
  const post = () => call("/api/scans", { method: "POST", headers: { Cookie: cookie, Origin: base, "Content-Type": "application/json" }, body: JSON.stringify(input) });
  assert.equal((await post()).status, 402);
  const grants = await Promise.all([1, 2, 3].map(() => grantCredits({ userId: user.id, amount: 9, reason: "ADJUSTMENT", externalId: tag })));
  assert.equal(grants.filter(x => x === "granted").length, 1);
  const requests = await Promise.all([post(), post()]);
  assert.deepEqual(requests.map(r => r.status).sort(), [201, 402]);
  const scan = await db.gridScan.findFirstOrThrow({ where: { userId: user.id }, include: { pins: true } });
  assert.equal(await db.pinDispatch.count({ where: { pin: { scanId: scan.id } } }), 9);
  const detail = await call(`/api/scans/${scan.id}`, { headers: { Cookie: cookie } });
  assert.equal(detail.status, 200);
  assert.equal((await detail.json()).pins.length, 9);
  const other = await db.user.create({ data: { email: `${tag}-other@example.invalid`, clerkId: tag } });
  const otherToken = randomBytes(32).toString("hex");
  await db.session.create({ data: { hash: sha(otherToken), userId: other.id, expiresAt: new Date(Date.now() + 60000) } });
  const otherCookie = `${cookie.split("=")[0]}=${otherToken}`;
  assert.equal((await call(`/api/scans/${scan.id}`, { headers: { Cookie: otherCookie } })).status, 404);
  assert.equal((await call(`/api/artifacts?key=fake.mp4`, { headers: { Cookie: otherCookie } })).status, 404);
  const result = { rankFound: 2, matchedDumpIdx: 0, topCompetitors: [], flags: [] };
  await Promise.all([completePin(scan.pins[0].id, scan.id, result), completePin(scan.pins[0].id, scan.id, result)]);
  await failPin(scan.pins[0].id, scan.id, "late failure");
  await Promise.all(scan.pins.slice(1).flatMap(p => [failPin(p.id, scan.id, "forced test failure"), failPin(p.id, scan.id, "duplicate failure")]));
  await completePin(scan.pins[1].id, scan.id, result);
  const final = await db.gridScan.findUniqueOrThrow({ where: { id: scan.id } });
  assert.equal(final.completedPins, 1); assert.equal(final.failedPins, 8); assert.equal(final.creditsRefunded, 8); assert.equal(final.status, "PARTIAL");
  const balance = (await db.user.findUniqueOrThrow({ where: { id: user.id } })).creditBalance;
  const ledger = await db.creditLedger.aggregate({ where: { userId: user.id }, _sum: { amount: true } });
  assert.equal(balance, 8); assert.equal(balance, ledger._sum.amount);
  const signOut = await call("/api/auth/sign-out", { method: "POST", headers: { Cookie: cookie, Origin: base } });
  assert.equal(signOut.status, 303);
  assert.equal((await call("/api/scans", { headers: { Cookie: cookie } })).status, 401);
  await db.user.deleteMany({ where: { id: { in: [user.id, other.id] } } });
  await db.loginToken.deleteMany({ where: { email } });
  console.log("PASS: email token expiry/replay, sessions/revocation, CSRF, zero signup credits, idempotent grants, concurrent credit holds, durable outbox, ownership isolation, atomic completion/refunds, ledger invariant");
}
main().finally(() => db.$disconnect()).catch(e => { console.error(e); process.exitCode = 1; });
